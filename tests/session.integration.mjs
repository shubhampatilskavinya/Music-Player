// Run against an isolated test server; this appends two fixture songs.
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
const base=process.env.APP_URL || 'http://localhost:3101';
const client=randomBytes(16).toString('hex');
const login=await fetch(base+'/api/auth/host',{method:'POST',headers:{'Content-Type':'application/json',Origin:base},body:JSON.stringify({pin:process.env.MIRC_HOST_PIN})});
assert.equal(login.status,200,'host login must succeed with MIRC_HOST_PIN set in the test environment');
const cookie=login.headers.get('set-cookie')?.split(';')[0];
assert.ok(cookie,'host login must set the identity cookie');
const post=async(command,requestId=randomBytes(16).toString('hex'))=>{
 const r=await fetch(base+'/api/session',{method:'POST',headers:{'Content-Type':'application/json',Origin:base,Cookie:cookie},body:JSON.stringify({client,requestId,command})});assert.equal(r.status,200);return r.json();
};
const before=await(await fetch(base+'/api/session')).json();
const a={type:'append',song:{title:'Append A',youtubeId:'M7lc1UVf-VE'}}, b={type:'append',song:{title:'Append B',youtubeId:'M7lc1UVf-VE'}};
const requestId=randomBytes(16).toString('hex');
await Promise.all([post(a,requestId),post(b)]);await post(a,requestId);
const after=await(await fetch(base+'/api/session')).json();
assert.equal(after.queue.length,before.queue.length+2);
assert.deepEqual(after.queue.slice(0,-2),before.queue);
assert.equal(after.index,before.index);
assert.deepEqual(new Set(after.queue.slice(-2).map(x=>x.title)),new Set(['Append A','Append B']));
assert.equal((await fetch(base+'/',{redirect:'manual'})).status,307,'host console must redirect to /login without a cookie');
assert.equal((await fetch(base+'/ipad',{redirect:'manual'})).status,307,'host console must redirect to /login without a cookie');
for(const route of ['/','/ipad'])assert.equal((await fetch(base+route,{headers:{Cookie:cookie}})).status,200);
assert.equal((await fetch(base+'/tv')).status,200,'the TV screen stays public');
const blocked=await fetch(base+'/api/session',{method:'POST',headers:{'Content-Type':'application/json',Origin:base},body:JSON.stringify({client,requestId:randomBytes(16).toString('hex'),command:a})});
assert.equal(blocked.status,403,'append without an identity cookie must be rejected');
const bad=await fetch(base+'/api/session',{method:'POST',headers:{Origin:'https://different.example','Content-Type':'application/json',Cookie:cookie},body:'{}'});assert.equal(bad.status,403);
const search=await(await fetch(base+'/api/search?q=M7lc1UVf-VE')).json();assert.equal(search.results[0].videoId,'M7lc1UVf-VE');
console.log('PASS: host login, concurrent append, preserved queue, retry idempotency, gated screen routes, origin validation, direct YouTube links');
